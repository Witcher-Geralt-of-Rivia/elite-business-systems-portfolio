-- 0001_init: Atomic CRM business schema ported from upstream supabase/schemas
-- (marmelab/atomic-crm @22f38f0f, MIT) onto plain PostgreSQL 16.
--
-- Differences from upstream (see docs/CRM_SUPABASE_MIGRATION.md):
--   * auth.users          -> crm.users (application-managed credentials)
--   * Supabase sessions   -> crm.sessions (opaque token, stored hashed)
--   * RLS policies        -> enforced in the API service layer (record-level rules)
--   * http / pg_net       -> not used; favicon/gravatar enrichment moved to the API
--   * storage.objects     -> crm.attachments (metadata) + local disk
--   * sales.administrator -> generated from sales.role (admin|manager|sales_rep|showcase)
--   * added: audit_log, password_reset_tokens, change notification trigger (SSE)

set search_path = crm;

-- ---------------------------------------------------------------- auth
create table users (
    id uuid primary key default gen_random_uuid(),
    email citext not null unique,
    password_hash text,
    created_at timestamptz not null default now(),
    last_login_at timestamptz,
    failed_login_count integer not null default 0,
    locked_until timestamptz
);

create table sessions (
    token_hash text primary key,                    -- sha256(token), never the token itself
    user_id uuid not null references users(id) on delete cascade,
    created_at timestamptz not null default now(),
    last_seen_at timestamptz not null default now(),
    expires_at timestamptz not null,
    ip inet,
    user_agent text
);
create index sessions_user_id_idx on sessions (user_id);
create index sessions_expires_at_idx on sessions (expires_at);

create table password_reset_tokens (
    token_hash text primary key,
    user_id uuid not null references users(id) on delete cascade,
    created_at timestamptz not null default now(),
    expires_at timestamptz not null,
    used_at timestamptz
);

-- ---------------------------------------------------------------- business tables (upstream 01_tables.sql)
create table sales (
    id bigint generated by default as identity primary key,
    first_name text not null default 'Pending',
    last_name text not null default 'Pending',
    email citext not null,
    role text not null default 'sales_rep'
        check (role in ('admin', 'manager', 'sales_rep', 'showcase')),
    administrator boolean generated always as (role = 'admin') stored,
    user_id uuid not null unique references users(id),
    avatar jsonb,
    disabled boolean not null default false,
    secondary_emails jsonb not null default '[]'::jsonb,
    constraint sales_secondary_emails_is_array check (jsonb_typeof(secondary_emails) = 'array')
);

create table companies (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    name text not null,
    sector text,
    size smallint,
    linkedin_url text,
    website citext,
    phone_number text,
    address text,
    zipcode text,
    city text,
    state_abbr text,
    sales_id bigint references sales(id),
    context_links json,
    country text,
    description text,
    revenue text,
    tax_identifier text,
    logo jsonb
);

create table contacts (
    id bigint generated by default as identity primary key,
    first_name text,
    last_name text,
    gender text,
    title text,
    background text,
    avatar jsonb,
    first_seen timestamptz,
    last_seen timestamptz,
    has_newsletter boolean,
    status text,
    tags bigint[],
    company_id bigint references companies(id) on update cascade on delete cascade,
    sales_id bigint references sales(id),
    linkedin_url text,
    email_jsonb jsonb,
    phone_jsonb jsonb
);

create table contact_notes (
    id bigint generated by default as identity primary key,
    contact_id bigint not null references contacts(id) on update cascade on delete cascade,
    text text,
    date timestamptz default now(),
    sales_id bigint references sales(id) on update cascade on delete cascade,
    status text,
    attachments jsonb[]
);

create table deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint references companies(id) on update cascade on delete cascade,
    contact_ids bigint[],
    categories text[],
    stage text not null,
    description text,
    amount bigint,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    archived_at timestamptz,
    expected_closing_date date,
    sales_id bigint references sales(id),
    index smallint,
    constraint deals_expected_closing_date_range
        check (expected_closing_date between '1900-01-01' and '2900-12-31')
);

create table deal_notes (
    id bigint generated by default as identity primary key,
    deal_id bigint not null references deals(id) on update cascade on delete cascade,
    type text,
    text text,
    date timestamptz default now(),
    sales_id bigint references sales(id),
    attachments jsonb[]
);

create table tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

create table tasks (
    id bigint generated by default as identity primary key,
    contact_id bigint not null references contacts(id) on update cascade on delete cascade,
    type text,
    text text,
    due_date timestamptz,
    done_date timestamptz,
    sales_id bigint references sales(id),
    created_at timestamptz not null default now()
);

create table configuration (
    id integer not null default 1 primary key,
    config jsonb not null default '{}'::jsonb,
    constraint configuration_singleton check (id = 1)
);
