-- ---------------------------------------------------------------- triggers
create function touch_updated_at() returns trigger language plpgsql as $$
begin
    new.updated_at := now();
    return new;
end $$;

create trigger deals_touch_updated_at before update on deals
    for each row execute function touch_updated_at();

-- Change feed for SSE (API LISTENs on channel crm_changes). Payload stays tiny (<8KB limit).
create function notify_change() returns trigger language plpgsql as $$
declare
    rec record;
begin
    rec := coalesce(new, old);
    perform pg_notify('crm_changes', json_build_object(
        'table', tg_table_name, 'op', lower(tg_op), 'id', rec.id)::text);
    return null;
end $$;

do $$
declare t text;
begin
    foreach t in array array['companies','contacts','contact_notes','deals','deal_notes','tasks','tags','sales']
    loop
        execute format('create trigger %I after insert or update or delete on %I
                        for each row execute function notify_change()', t || '_notify', t);
    end loop;
end $$;

-- ---------------------------------------------------------------- views (upstream 03_views.sql)
create view companies_summary as
select c.*, count(distinct d.id) as nb_deals, count(distinct co.id) as nb_contacts
from companies c
    left join deals d on c.id = d.company_id
    left join contacts co on c.id = co.company_id
group by c.id;

create view contacts_summary as
select
    co.*,
    (jsonb_path_query_array(co.email_jsonb, '$[*]."email"'))::text as email_fts,
    (jsonb_path_query_array(co.phone_jsonb, '$[*]."number"'))::text as phone_fts,
    c.name as company_name,
    count(distinct t.id) filter (where t.done_date is null) as nb_tasks
from contacts co
    left join tasks t on co.id = t.contact_id
    left join companies c on co.company_id = c.id
group by co.id, c.name;

create view activity_log as
select ('company.' || c.id || '.created') as id, 'company.created' as type, c.created_at as date,
       c.id as company_id, c.sales_id, to_json(c.*) as company,
       null::json as contact, null::json as deal, null::json as contact_note, null::json as deal_note
from companies c
union all
select ('contact.' || co.id || '.created'), 'contact.created', co.first_seen,
       co.company_id, co.sales_id, null, to_json(co.*), null, null, null
from contacts co
union all
select ('contactNote.' || cn.id || '.created'), 'contactNote.created', cn.date,
       co.company_id, cn.sales_id, null, null, null, to_json(cn.*), null
from contact_notes cn left join contacts co on co.id = cn.contact_id
union all
select ('deal.' || d.id || '.created'), 'deal.created', d.created_at,
       d.company_id, d.sales_id, null, null, to_json(d.*), null, null
from deals d
union all
select ('dealNote.' || dn.id || '.created'), 'dealNote.created', dn.date,
       d.company_id, dn.sales_id, null, null, null, null, to_json(dn.*)
from deal_notes dn left join deals d on d.id = dn.deal_id;

create view init_state as
select count(sub.id) as is_initialized from (select id from sales limit 1) sub;
