create table attachments (
    id uuid primary key default gen_random_uuid(),
    storage_path text not null unique,          -- relative to the attachment root; server-generated
    original_name text not null,
    mime_type text,
    size_bytes bigint not null,
    sha256 text not null,
    uploaded_by bigint references sales(id),
    created_at timestamptz not null default now()
);

create table audit_log (
    id bigint generated always as identity primary key,
    at timestamptz not null default now(),
    actor_sales_id bigint references sales(id),
    actor_kind text not null default 'user' check (actor_kind in ('user', 'simulator', 'system')),
    action text not null,                       -- create | update | delete | login | login_failed | logout | ...
    resource text,
    record_id text,
    changes jsonb,
    ip inet
);
create index audit_log_at_idx on audit_log (at desc);
create index audit_log_resource_idx on audit_log (resource, record_id);

